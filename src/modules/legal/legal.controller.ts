/**
 * Legal pages, served as HTML from this server.
 *
 * ── Why they live here ──────────────────────────────────────────────────────
 * Google Play will not accept a listing for an app that collects photos
 * without a live privacy policy URL, and it separately requires a
 * web-accessible route for requesting account deletion. Serving both from the
 * API means they exist the moment the server is deployed — no second host, no
 * domain to buy, no static-site pipeline, and no risk of the policy saying one
 * thing while the code does another, because they are versioned together.
 *
 * The policy below describes what this server ACTUALLY does, verified against
 * the avatars service rather than copied from a template: the source photo is
 * deleted as soon as generation finishes, consent is recorded with a timestamp
 * and policy version, and media is served only behind a signed, expiring URL.
 *
 * Deliberately NOT legal advice. It is an accurate description of the data flow
 * written so a reviewer and a player can both follow it; have a lawyer read it
 * before a production launch.
 */
import { Controller, Get, Header, Res } from '@nestjs/common';
import type { Response } from 'express';
import { POLICY_VERSION } from '../avatars/avatars.service';

const CONTACT = process.env.LUDO_CONTACT_EMAIL ?? 'privacy@ludoafterdark.app';
const APP_NAME = 'Ludo After Dark';

/** One stylesheet, inlined: a legal page that needs a CDN is a legal page that can fail to load. */
const STYLE = `
  :root { color-scheme: dark; }
  body {
    margin: 0 auto; padding: 2.5rem 1.25rem 4rem; max-width: 46rem;
    background: #0A0B10; color: #E6E7EE;
    font: 16px/1.65 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
  }
  h1 { font-size: 1.75rem; margin: 0 0 .25rem; color: #FFF; }
  h2 { font-size: 1.1rem; margin: 2.25rem 0 .5rem; color: #00FF87; }
  .meta { color: #8A8DA0; font-size: .875rem; margin-bottom: 2rem; }
  a { color: #00FF87; }
  ul { padding-left: 1.25rem; }
  li { margin: .35rem 0; }
  code { background: #15161F; padding: .1rem .35rem; border-radius: .25rem; font-size: .9em; }
  .box { background: #15161F; border: 1px solid #23252F; border-radius: .75rem; padding: 1rem 1.25rem; margin: 1.5rem 0; }
  footer { margin-top: 3rem; color: #8A8DA0; font-size: .8125rem; }
`;

function page(title: string, body: string) {
  return `<!doctype html>
<html lang="en"><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title} — ${APP_NAME}</title>
<style>${STYLE}</style>
</head><body>${body}
<footer>${APP_NAME} · Policy version ${POLICY_VERSION} · <a href="/privacy">Privacy</a> · <a href="/account-deletion">Delete your account</a></footer>
</body></html>`;
}

@Controller()
export class LegalController {
  @Get('privacy')
  @Header('Cache-Control', 'public, max-age=3600')
  privacy(@Res() res: Response) {
    res.type('html').send(
      page(
        'Privacy Policy',
        `
<h1>Privacy Policy</h1>
<p class="meta">Policy version ${POLICY_VERSION}. Applies to the ${APP_NAME} mobile app and its server.</p>

<p>This policy describes exactly what ${APP_NAME} collects, why, how long it is kept,
and how to delete it. It is written to match what the software does.</p>

<h2>What we collect</h2>
<ul>
  <li><strong>A device identifier.</strong> Generated by our server on first launch and stored on
      your device. It is how we recognise your account when you reopen the app. It is not
      an advertising identifier and is not shared.</li>
  <li><strong>A display name.</strong> Shown to other players in a match. You choose it.</li>
  <li><strong>A photo, only if you create an avatar.</strong> You must tap to give explicit
      consent first; the app records the time you consented and the version of this policy
      you agreed to.</li>
  <li><strong>Gameplay data.</strong> Match results, dice rolls and progression, so a match can
      be played and scored.</li>
</ul>

<div class="box">
  <strong>We do not collect</strong> your contacts, your location, your advertising ID, your
  browsing activity, or any analytics about other apps on your device. There are no
  third-party advertising or tracking SDKs in this app.
</div>

<h2>Photos, specifically</h2>
<ul>
  <li>A photo is uploaded only when you ask for an avatar to be generated, and only after
      you give explicit consent.</li>
  <li>It is sent to an AI image provider for the sole purpose of generating your avatar.</li>
  <li><strong>The source photo is deleted from our servers as soon as generation
      finishes</strong> — whether it succeeded or failed. We keep the generated avatar
      image, not your photograph.</li>
  <li>We do not use your photo to train any model, and we do not use it for anything other
      than producing the avatar you asked for.</li>
  <li>Generated avatars are served only through signed URLs that expire. They are not
      publicly browsable.</li>
</ul>

<h2>Who else sees your data</h2>
<ul>
  <li><strong>Other players</strong> see your display name, your avatar and your moves in a
      match. Nothing else.</li>
  <li><strong>Our hosting and AI providers</strong> process data on our behalf in order to run
      the service. They are not permitted to use it for their own purposes.</li>
  <li>We do not sell your data, and we do not share it for advertising.</li>
</ul>

<h2>How long we keep it</h2>
<ul>
  <li>Source photos: deleted immediately after avatar generation completes.</li>
  <li>Account, avatars and progression: until you delete them.</li>
  <li>Server logs: short-lived operational logs, which may briefly contain your user id.</li>
</ul>

<h2>Your choices</h2>
<ul>
  <li><strong>Delete an avatar</strong> — in the app, under Profile.</li>
  <li><strong>Delete every avatar and any pending photo</strong> — Settings → Privacy &amp; your data.</li>
  <li><strong>Delete your whole account</strong> — Settings → Delete account, or see
      <a href="/account-deletion">how to request deletion</a>. This cannot be undone.</li>
  <li><strong>Refuse photo collection entirely</strong> — avatar creation is optional; the game
      is fully playable without it.</li>
</ul>

<h2>Children</h2>
<p>${APP_NAME} is not directed at children under 13, and we do not knowingly collect their
data. If you believe a child has created an account, contact us and we will delete it.</p>

<h2>Changes</h2>
<p>If we change what we collect, we raise the policy version and ask for consent again before
collecting anything new under it. The current version is <code>${POLICY_VERSION}</code>.</p>

<h2>Contact</h2>
<p>Questions, or a data request: <a href="mailto:${CONTACT}">${CONTACT}</a>.</p>
`,
      ),
    );
  }

  /**
   * The web-accessible deletion route Google Play requires, in addition to the
   * in-app control. A reviewer must be able to reach this without installing
   * the app, so it describes both paths and names what each one removes.
   */
  @Get('account-deletion')
  @Header('Cache-Control', 'public, max-age=3600')
  accountDeletion(@Res() res: Response) {
    res.type('html').send(
      page(
        'Delete your account',
        `
<h1>Delete your account</h1>
<p class="meta">${APP_NAME} · two ways to delete, both permanent.</p>

<h2>In the app</h2>
<p>Open <strong>Settings → Delete account</strong>. You will be asked to confirm. Deletion is
immediate and cannot be undone.</p>

<h2>By email</h2>
<p>If you no longer have the app installed, email
<a href="mailto:${CONTACT}">${CONTACT}</a> from any address and include your in-game display
name. We will ask you for the user id shown in the app's Settings screen if we need to
confirm which account is yours, and we will delete it within 30 days.</p>

<div class="box">
  <strong>What deletion removes:</strong> your account, your display name, your device
  identifier, every avatar you generated, your progression and your match history.
  <br><br>
  <strong>What is already gone:</strong> any photo you uploaded. Source photos are deleted as
  soon as avatar generation finishes, so there is never one waiting to be removed.
  <br><br>
  <strong>What we may briefly retain:</strong> short-lived server logs, which age out on their
  own, and anything we are required to keep by law.
</div>

<p>Deleting your account does not delete it from other players' memories of losing to you.
It does remove your name from leaderboards.</p>

<p><a href="/privacy">Read the privacy policy</a></p>
`,
      ),
    );
  }
}
